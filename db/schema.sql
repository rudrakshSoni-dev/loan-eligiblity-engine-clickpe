-- Loan Eligibility Engine — database schema (PostgreSQL 16).
--
-- Conventions
--   * Status columns are text + CHECK, not ENUM: adding a value is a one-line
--     constraint swap, and a new ENUM value cannot be used inside the
--     transaction that adds it.
--   * CHECK ranges are deliberately looser than the sample data (docs/data-notes.md)
--     so valid future uploads are not rejected; exact rules live in validation code.
--   * A NULL product criterion means "unconstrained" (Stage 1 relies on this).
--   * updated_at is maintained by one trigger, so no write path can forget it.

CREATE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------------
-- Ingestion
-- ---------------------------------------------------------------------------

-- One row per uploaded CSV. chunks_done / rows_* are display values for the UI;
-- completion is decided from chunk_loads, never from these counters.
CREATE TABLE upload_batches (
    id            uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    s3_key        text        NOT NULL UNIQUE,
    status        text        NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'splitting', 'loading', 'processed', 'failed',
                          'matching', 'matched', 'notifying', 'notified')),
    total_chunks  integer     CHECK (total_chunks > 0),  -- NULL until the split is known
    chunks_done   integer     NOT NULL DEFAULT 0 CHECK (chunks_done >= 0),
    rows_ok       integer     NOT NULL DEFAULT 0 CHECK (rows_ok >= 0),
    rows_rejected integer     NOT NULL DEFAULT 0 CHECK (rows_rejected >= 0),
    error         text,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CHECK (chunks_done <= total_chunks)
);

-- Idempotency ledger: one row per chunk, written in the chunk's own transaction.
-- An SQS redelivery hits the primary key and becomes a no-op.
CREATE TABLE chunk_loads (
    batch_id      uuid        NOT NULL REFERENCES upload_batches (id) ON DELETE CASCADE,
    chunk_no      integer     NOT NULL CHECK (chunk_no >= 0),
    rows_ok       integer     NOT NULL CHECK (rows_ok >= 0),
    rows_rejected integer     NOT NULL CHECK (rows_rejected >= 0),
    loaded_at     timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (batch_id, chunk_no)
);

-- Reject report: the first N bad rows per batch (N is capped in code).
CREATE TABLE rejected_rows (
    batch_id uuid    NOT NULL REFERENCES upload_batches (id) ON DELETE CASCADE,
    line_no  integer NOT NULL CHECK (line_no >= 1),  -- 1-based line in the CSV file
    reason   text    NOT NULL,
    raw      text,
    PRIMARY KEY (batch_id, line_no)
);

-- email is NOT unique: in the sample each address is shared by 2–5 users,
-- so user_id is the only natural key. batch_id = the batch that last changed the row.
CREATE TABLE users (
    user_id           uuid          PRIMARY KEY,
    name              text          NOT NULL CHECK (btrim(name) <> ''),
    email             text          NOT NULL
        CHECK (email = lower(btrim(email)) AND email ~ '^[^@[:space:]]+@[^@[:space:]]+$'),
    monthly_income    numeric(12,2) NOT NULL CHECK (monthly_income > 0),
    credit_score      smallint      NOT NULL CHECK (credit_score BETWEEN 300 AND 900),
    employment_status text          NOT NULL
        CHECK (employment_status IN ('Salaried', 'Self-Employed', 'Business')),
    age               smallint      NOT NULL CHECK (age BETWEEN 18 AND 100),
    batch_id          uuid          NOT NULL REFERENCES upload_batches (id),
    created_at        timestamptz   NOT NULL DEFAULT now(),
    updated_at        timestamptz   NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Products (Workflow A)
-- ---------------------------------------------------------------------------

-- Products are never deleted: unseen ones are set active = false, so matches
-- keep a valid product_id.
CREATE TABLE loan_products (
    id                 integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source             text          NOT NULL,
    product_name       text          NOT NULL,
    source_url         text,
    interest_rate_min  numeric(5,2)  CHECK (interest_rate_min >= 0),
    interest_rate_max  numeric(5,2)  CHECK (interest_rate_max <= 100),
    min_monthly_income numeric(12,2) CHECK (min_monthly_income >= 0),
    min_credit_score   smallint      CHECK (min_credit_score BETWEEN 300 AND 900),
    max_credit_score   smallint      CHECK (max_credit_score BETWEEN 300 AND 900),
    min_age            smallint      CHECK (min_age BETWEEN 18 AND 100),
    max_age            smallint      CHECK (max_age BETWEEN 18 AND 100),
    -- NULL = any employment; an empty array would silently match nobody.
    allowed_employment text[]
        CHECK (cardinality(allowed_employment) > 0
               AND allowed_employment <@ ARRAY['Salaried', 'Self-Employed', 'Business']),
    raw_criteria_text  text,
    content_hash       text          CHECK (content_hash ~ '^[0-9a-f]{64}$'),  -- SHA-256 hex
    parse_confidence   real          CHECK (parse_confidence BETWEEN 0 AND 1),
    is_seed            boolean       NOT NULL DEFAULT false,
    active             boolean       NOT NULL DEFAULT true,
    last_seen_at       timestamptz,
    created_at         timestamptz   NOT NULL DEFAULT now(),
    updated_at         timestamptz   NOT NULL DEFAULT now(),
    UNIQUE (source, product_name),
    CHECK (interest_rate_min <= interest_rate_max),
    CHECK (min_credit_score <= max_credit_score),
    CHECK (min_age <= max_age)
);

CREATE TABLE crawl_runs (
    id             bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source         text        NOT NULL,
    status         text        NOT NULL CHECK (status IN ('ok', 'failed')),
    products_found integer     CHECK (products_found >= 0),
    changed        boolean,    -- false = content hash unchanged, LLM skipped
    llm_calls      integer     NOT NULL DEFAULT 0 CHECK (llm_calls >= 0),
    error          text,
    ran_at         timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Matching (Workflow B) and notification (Workflow C)
-- ---------------------------------------------------------------------------

-- Only eligible pairs are stored. stage = what decided it: deterministic rules
-- (Stages 1–2) or an LLM cohort verdict (Stage 3).
CREATE TABLE matches (
    user_id     uuid        NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    product_id  integer     NOT NULL REFERENCES loan_products (id),
    stage       text        NOT NULL CHECK (stage IN ('rules', 'llm')),
    reason      text        NOT NULL,
    batch_id    uuid        NOT NULL REFERENCES upload_batches (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    notified_at timestamptz,  -- NULL = email not sent yet
    PRIMARY KEY (user_id, product_id)
);

-- One row per Workflow B run: the measured funnel for the Treasure Hunt.
-- Counters stay NULL until their stage has run, so "0" always means measured zero.
CREATE TABLE pipeline_runs (
    id                bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    batch_id          uuid        NOT NULL REFERENCES upload_batches (id),
    total_pairs       integer     CHECK (total_pairs >= 0),
    stage1_pairs      integer     CHECK (stage1_pairs >= 0),
    stage2_clear      integer     CHECK (stage2_clear >= 0),
    stage2_borderline integer     CHECK (stage2_borderline >= 0),
    llm_cohorts       integer     CHECK (llm_cohorts >= 0),
    cache_hits        integer     CHECK (cache_hits >= 0),
    llm_calls         integer     CHECK (llm_calls >= 0),
    llm_tokens        integer     CHECK (llm_tokens >= 0),
    unresolved_budget integer     CHECK (unresolved_budget >= 0),
    final_matches     integer     CHECK (final_matches >= 0),
    stage_ms          jsonb       NOT NULL DEFAULT '{}'::jsonb,
    started_at        timestamptz NOT NULL DEFAULT now(),
    finished_at       timestamptz,
    CHECK (finished_at >= started_at)
);

-- Cross-run LLM cache. Keyed by the product's content hash, so a changed
-- product invalidates its verdicts without any explicit purge.
CREATE TABLE cohort_verdicts (
    cohort_key           text        NOT NULL,
    product_content_hash text        NOT NULL CHECK (product_content_hash ~ '^[0-9a-f]{64}$'),
    eligible             boolean     NOT NULL,
    reason               text        NOT NULL,
    model                text        NOT NULL,
    created_at           timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (cohort_key, product_content_hash)
);

-- Per-call token ledger (LLM Gateway). batch_id is NULL for crawl-time calls.
CREATE TABLE llm_calls (
    id                bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    purpose           text        NOT NULL CHECK (btrim(purpose) <> ''),
    model             text        NOT NULL,
    prompt_tokens     integer     CHECK (prompt_tokens >= 0),      -- NULL when the call failed
    completion_tokens integer     CHECK (completion_tokens >= 0),
    status            integer     NOT NULL CHECK (status BETWEEN 0 AND 599),  -- HTTP; 0 = no response
    latency_ms        integer     CHECK (latency_ms >= 0),
    batch_id          uuid        REFERENCES upload_batches (id),
    created_at        timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Triggers and indexes
-- ---------------------------------------------------------------------------

CREATE TRIGGER upload_batches_updated_at BEFORE UPDATE ON upload_batches
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER loan_products_updated_at BEFORE UPDATE ON loan_products
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE INDEX users_batch_id_idx        ON users (batch_id);                      -- users of a batch (Stage 1)
CREATE INDEX users_score_income_idx    ON users (credit_score, monthly_income);  -- range pre-filter
CREATE INDEX matches_unnotified_idx    ON matches (user_id) WHERE notified_at IS NULL;  -- Workflow C queue
CREATE INDEX matches_batch_id_idx      ON matches (batch_id);                    -- batch-status counts
CREATE INDEX loan_products_active_idx  ON loan_products (active);
CREATE INDEX pipeline_runs_batch_id_idx ON pipeline_runs (batch_id);
CREATE INDEX llm_calls_batch_id_idx    ON llm_calls (batch_id);
